// UI language: English or Simplified Chinese, switched from the header (EN / 中文).
// A tiny shared store (kept in localStorage on web, for the session on native) is the default; each phone then
// scopes its own language from that person's saved prefs (LangScope below), so the toggle is per person.
// What the assistant says follows the language the user writes in (the server decides); this only changes the
// app's own labels, plus server vocabulary that maps one to one (account names, categories, providers, warning
// signs). Longer server text such as risk and compliance reasons stays in English.
import { createContext, useContext, useSyncExternalStore } from 'react';
import { Platform } from 'react-native';

export type Lang = 'en' | 'zh';

const KEY = 'homebridge.lang';

function load(): Lang {
  if (Platform.OS !== 'web') return 'en';
  try {
    const v = globalThis.localStorage?.getItem(KEY);
    return v === 'zh' ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

let current: Lang = load();
const listeners = new Set<() => void>();

function applyDocumentLang(l: Lang) {
  if (Platform.OS !== 'web') return;
  try {
    globalThis.document?.documentElement?.setAttribute('lang', l === 'zh' ? 'zh-CN' : 'en');
  } catch {
    /* no DOM */
  }
}
applyDocumentLang(current);

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang) {
  if (l === current) return;
  current = l;
  applyDocumentLang(l);
  if (Platform.OS === 'web') {
    try {
      globalThis.localStorage?.setItem(KEY, l);
    } catch {
      /* private window or blocked storage: the choice lasts for this session */
    }
  }
  listeners.forEach((f) => f());
}

function subscribe(f: () => void) {
  listeners.add(f);
  return () => {
    listeners.delete(f);
  };
}

// Each person picks a language at onboarding (saved in their prefs on the server), so each demo phone can show its
// own: a phone wraps itself in <LangScope value={lang}>. Outside any scope (the stage chrome) the shared store applies.
const LangCtx = createContext<Lang | null>(null);
export const LangScope = LangCtx.Provider;

export function useLang(): Lang {
  const scoped = useContext(LangCtx);
  const shared = useSyncExternalStore(subscribe, getLang, getLang);
  return scoped ?? shared;
}

