function data(lang: Lang, s: string): string {
  if (lang !== 'zh' || !s) return s;
  const hit = DATA_ZH[s];
  if (hit) return hit;
  const term = /^(Winter|Summer|Fall|Spring) Term (\d), installment (\d)$/.exec(s);
  if (term) {
    const season = { Winter: '冬季', Summer: '夏季', Fall: '秋季', Spring: '春季' }[term[1]];
    return `${season}第${term[2]}学期第${term[3]}期`;
  }
  const model = /^Wording similar to known scams \((\d+)%\)$/.exec(s);
  if (model) return `措辞与已知诈骗相似（${model[1]}%）`;
  // The two warnings most drafts carry
  const low = /^Balance in (.+) is lower than this amount(?: right now)?; it will fail( unless topped up(?: first)?)?\.$/.exec(s);
  if (low) return `${data('zh', low[1])}的余额低于这笔金额，${low[2] ? '除非先补足，否则' : ''}会失败。`;
  const margin = /^Rate ([\d.]+) includes a ([\d.]+)% margin over mid-market \(([\d.]+)\)\.$/.exec(s);
  if (margin) return `汇率 ${margin[1]} 含有比中间价（${margin[3]}）高 ${margin[2]}% 的汇差。`;
  return s;
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** '2026-12-16' as 'Dec 16' or '12月16日'. */
export function shortDate(lang: Lang, iso: string): string {
  const m = Number(iso.slice(5, 7));
  const d = Number(iso.slice(8, 10));
  return lang === 'zh' ? `${m}月${d}日` : `${MONTHS[m - 1]} ${d}`;
}

const SUMMARY_ZH: [RegExp, (m: RegExpExecArray) => string][] = [
  [/^Pay (\w{3} [\d,.]+) to (.+) from (.+)$/, (m) => `从 ${data('zh', m[3])} 向 ${m[2]} 支付 ${m[1]}`],
  [/^Move (\w{3} [\d,.]+) from (.+) to (.+)$/, (m) => `把 ${m[1]} 从 ${data('zh', m[2])} 转到 ${data('zh', m[3])}`],
  [
    /^Convert (\w{3} [\d,.]+) to about (\w{3} [\d,.]+) \((.+) to (.+)\)$/,
    (m) => `把 ${m[1]} 兑换成约 ${m[2]}（${data('zh', m[3])} → ${data('zh', m[4])}）`,
  ],
  [/^Ask sponsor for (\w{3} [\d,.]+): (.*)$/, (m) => `向担保人申请 ${m[1]}：${m[2]}`],
  [/^Add new payee (.+)$/, (m) => `添加新收款人 ${m[1]}`],
];

/** An action summary from the policy engine ("Pay CAD 45.00 to BC Hydro from CAD Everyday") in the UI language. */
function summary(lang: Lang, s: string): string {
  if (lang !== 'zh') return s;
  for (const [re, fn] of SUMMARY_ZH) {
    const m = re.exec(s);
    if (m) return fn(m);
  }
  return s;
}

export type T = ((key: Key, vars?: Record<string, string | number>) => string) & {
  lang: Lang;
  /** Server vocabulary (account names, categories, providers, warning signs) in the UI language. */
  d: (s: string) => string;
  /** An action summary in the UI language. */
  summary: (s: string) => string;
  date: (iso: string) => string;
};

export function makeT(lang: Lang): T {
  const fn = ((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars)) as T;
  fn.lang = lang;
  fn.d = (s: string) => data(lang, s);
  fn.summary = (s: string) => summary(lang, s);
  fn.date = (iso: string) => shortDate(lang, iso);
  return fn;
}

const CACHE: Record<Lang, T> = { en: makeT('en'), zh: makeT('zh') };

/** The translator for the current UI language; components re-render when it changes. */
export function useT(): T {
  return CACHE[useLang()];
}
